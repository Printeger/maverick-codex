#!/usr/bin/env python3
"""Project-local Maverick installation and explicit personality updates. Python 3.11+."""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

try:
    import tomllib
except ImportError:
    raise SystemExit("Maverick requires Python 3.11 or newer (stdlib tomllib).")

VERSION = "1.0.0"
ROLES = ("maverick", "rebel", "inventor", "hacker", "scientist", "producer")
CHILDREN = ROLES[1:]
START = "<!-- maverick-codex:start -->"
END = "<!-- maverick-codex:end -->"
GENERATED = "# Generated by Maverick Codex. Edit persona preferences, then run sync.\n"
DESCRIPTIONS = {
    "rebel": "Challenge inherited assumptions; distinguish real constraints from convention.",
    "inventor": "Find cross-disciplinary mechanisms and one cheap experiment, not decorative analogies.",
    "hacker": "Build the shortest useful implementation; avoid speculative abstractions and process.",
    "scientist": "Resolve a material factual doubt with discriminating evidence; do not demand exhaustive tests.",
    "producer": "Remove a concrete delivery bottleneck; do not invent a process department.",
}


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def js(value) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def source_layout() -> tuple[Path, Path, Path, Path]:
    root = Path(__file__).resolve().parent.parent
    if (root / "references/personas").is_dir():
        return root, root / "references/personas", root / "references/knowledge", root / "SKILL.md"
    return root, root / "personas", root / "knowledge", root / "skills/maverick/SKILL.md"


def skill_dir(project: Path) -> Path:
    return project / ".agents/skills/maverick"


def manifest(project: Path) -> dict:
    path = project / ".maverick/manifest.json"
    if not path.exists():
        raise ValueError("This project is not initialized. Run init first.")
    data = json.loads(read(path))
    if not isinstance(data, dict) or data.get("format") != 1:
        raise ValueError("Unsupported Maverick installation format; no files changed.")
    return data


def preferences(project: Path) -> dict:
    path = project / ".maverick/preferences.json"
    data = json.loads(read(path)) if path.exists() else {}
    if not isinstance(data, dict) or set(data) - set(ROLES):
        raise ValueError("preferences.json must map known persona names to rule dictionaries.")
    for role, rules in data.items():
        if not isinstance(rules, dict) or len(rules) > 8:
            raise ValueError(f"{role}: use at most eight named rules; replace old rules instead of accumulating them.")
        for key, value in rules.items():
            if not re.fullmatch(r"[a-z][a-z0-9_-]{0,39}", key) or not isinstance(value, str) or not value.strip() or len(value) > 700:
                raise ValueError(f"Invalid preference: {role}.{key}")
    return data


def root_block() -> str:
    return f"""{START}
## Maverick for this project

Only the main coordinator adopts Maverick. Delegated children keep their assigned
persona; all agents follow the user's request and the project's existing constraints.

At the start of a session, read `.agents/skills/maverick/SKILL.md`, then the relevant
persona in `.agents/skills/maverick/references/personas/`, `.maverick/PROJECT.md`,
and `.maverick/STATE.md`. Read `.maverick/preferences.json` for this project's
explicit personality adjustments. Use the knowledge index to load only relevant facts.

Maverick is the default voice: choose a direction, explain it plainly, and act.
Handle small work directly. Delegate only bounded work with a net benefit, normally
at most two children. Do not run a six-agent committee. Reuse an existing child only
for the same active workstream; thread reuse never substitutes for persisted state.
Use `mav_rebel`, `mav_inventor`, `mav_hacker`, `mav_scientist`, `mav_producer` when
native custom agents are available. Never claim native role loading from a task name alone.

Default to a useful prototype. Add tests, abstractions, compatibility layers or process
only for a concrete need or an existing requirement. Do not create branches, commits,
backup copies or changelogs during ordinary project work unless requested or necessary.
Personality updates happen only on an explicit `update` request; there is no schedule.
{END}"""


def merge_guidance(text: str) -> str:
    if START in text or END in text:
        if text.count(START) != 1 or text.count(END) != 1 or text.index(END) < text.index(START):
            raise ValueError("AGENTS.md has incomplete Maverick markers; resolve them before initialization.")
        return text[:text.index(START)] + root_block() + text[text.index(END) + len(END):]
    return text + ("\n\n" if text and not text.endswith("\n\n") else "") + root_block() + "\n"


def merge_config(text: str) -> str:
    data = tomllib.loads(text)
    agents = data.get("agents", {})
    if not isinstance(agents, dict):
        raise ValueError("The existing agents configuration is not a TOML table.")
    if "max_threads" in agents and "max_concurrent_threads_per_session" in agents:
        raise ValueError("Both aliases for agent concurrency are present; keep one before init.")
    header = re.search(r"(?m)^\[agents\][ \t]*(?:#.*)?$", text)
    if not header:
        if agents:
            raise ValueError("Existing agents config uses inline/dotted tables. Convert it to [agents] before init; no files changed.")
        result = text + ("\n" if text and not text.endswith("\n\n") else "")
        result += "[agents]\nenabled = true\nmax_concurrent_threads_per_session = 2\n"
    else:
        after = header.end()
        next_table = re.search(r"(?m)^\s*\[", text[after:])
        end = after + next_table.start() if next_table else len(text)
        body = text[after:end]
        if "enabled" in agents:
            if agents["enabled"] is not True:
                body, count = re.subn(r"(?m)^(\s*enabled\s*=\s*)false\b", r"\g<1>true", body, count=1)
                if count != 1:
                    raise ValueError("Cannot safely enable existing agents table; no files changed.")
        else:
            body += ("\n" if not body.endswith("\n") else "") + "enabled = true\n"
        if "max_threads" not in agents and "max_concurrent_threads_per_session" not in agents:
            body += ("\n" if not body.endswith("\n") else "") + "max_concurrent_threads_per_session = 2\n"
        result = text[:after] + body + text[end:]
    parsed = tomllib.loads(result)
    if parsed.get("agents", {}).get("enabled") is not True:
        raise ValueError("Agents are not enabled in the resulting project config.")
    return result


def compiled_role(role: str, persona: str, prefs: dict, worker_model: str | None) -> str:
    instruction = persona.rstrip()
    if prefs.get(role):
        instruction += "\n\n## Explicit project preferences\n" + "\n".join(f"- {k}: {v}" for k, v in prefs[role].items())
    instruction += """

## Runtime contract
You are this delegated persona, not the root Maverick. Read `.maverick/PROJECT.md`
and the relevant entries of `.maverick/knowledge/INDEX.md`; load details on demand.
Follow the parent's task scope and file ownership. Do not redo the whole project survey.
Give the parent the useful conclusion, changed paths or source evidence, actual verification,
and unresolved blocker. Usually keep the report under 180 words unless evidence needs more.
Do not spawn further agents or require repeated consensus unless explicitly delegated.
Do not edit personality rules without an explicit user update request.
"""
    if role == "inventor":
        instruction += """
Your knowledge is not confined to the project domain. Consult
`.agents/skills/maverick/references/knowledge/INDEX.md`. For open-ended invention,
try a relevant neighboring field and one structurally useful distant field. Read only
the selected cards. State the transferred mechanism, assumptions and one cheap test.
An analogy is a hypothesis, not evidence of feasibility or novelty.
"""
    result = GENERATED + f'name = "mav_{role}"\n'
    result += "description = " + json.dumps(DESCRIPTIONS[role]) + "\n"
    if role == "hacker" and worker_model:
        result += "model = " + json.dumps(worker_model) + "\n"
    result += "developer_instructions = " + json.dumps(instruction, ensure_ascii=False) + "\n"
    tomllib.loads(result)
    return result


def ensure_owned(path: Path, content: str, generated: bool = False) -> None:
    if not path.exists() or read(path) == content:
        return
    if generated and read(path).startswith(GENERATED):
        return
    raise ValueError(f"Will not overwrite an unrelated or locally edited file: {path}")


def write_all(project: Path, files: dict[Path, str]) -> list[str]:
    # Preflight every path before writing. Never follow a symlink out of the project.
    for path in files:
        if not path.resolve().is_relative_to(project):
            raise ValueError(f"Managed path resolves outside the project: {path}")
        if path.exists() and not path.is_file():
            raise ValueError(f"Expected a file: {path}")
    changed = []
    for path, content in files.items():
        if path.exists() and read(path) == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        changed.append(str(path.relative_to(project)))
    return changed


def init(args) -> dict:
    project = args.project
    if not project.is_dir():
        raise ValueError(f"Project directory does not exist: {project}")
    existing = (project / ".maverick/manifest.json").exists()
    if existing:
        manifest(project)
        if args.worker_model:
            raise ValueError("Already installed. Use sync --worker-model MODEL to change the worker model.")
        return {"status": "already_initialized", "changed": [], "next": "Run doctor; continue adaptation if pending."}
    root, personas, knowledge, skill = source_layout()
    required = [skill, *(personas / f"{r}.md" for r in ROLES), knowledge / "INDEX.md"]
    for path in required:
        if not path.is_file():
            raise ValueError(f"Incomplete source package: {path}")
    dest = skill_dir(project)
    files = {
        dest / "SKILL.md": read(skill),
        dest / "scripts/maverick.py": read(Path(__file__).resolve()),
    }
    metadata = skill.parent / "agents/openai.yaml"
    if metadata.is_file():
        files[dest / "agents/openai.yaml"] = read(metadata)
    for path in sorted(personas.glob("*.md")):
        files[dest / "references/personas" / path.name] = read(path)
    for path in sorted(knowledge.glob("*.md")):
        files[dest / "references/knowledge" / path.name] = read(path)
    files[project / ".maverick/manifest.json"] = js({
        "format": 1, "version": VERSION, "installed_at": now(), "worker_model": args.worker_model,
        "native_roles": ["mav_" + r for r in CHILDREN],
    })
    files[project / ".maverick/preferences.json"] = "{}\n"
    files[project / ".maverick/PROJECT.md"] = f"""# {args.name or project.name}

Status: PENDING

## Goal and scope
Fill from the user's request and the actual project. Keep explicit non-goals and constraints short.

## Source map
List a few real repository paths and what each establishes. Do not invent files or results.

## Working conventions
Record the actual entry point, relevant commands, data locations (no credentials), and current limitations.
Default to a useful prototype unless the user or this project requires otherwise.
"""
    files[project / ".maverick/knowledge/INDEX.md"] = """# Project knowledge

- [Domain background](domain.md): project-specific concepts, tools, source references and unknowns.
- Cross-disciplinary atlas: `.agents/skills/maverick/references/knowledge/INDEX.md`.

Read only the documents relevant to the task. The atlas supplements this domain; it is never replaced by it.
Project facts and technical knowledge belong here, not in personality preferences.
"""
    files[project / ".maverick/knowledge/domain.md"] = """# Domain background

Status: PENDING

## What this project actually uses
Extract the domain, libraries, conventions and technical constraints from real sources.

## References
Point to repository paths or verified primary documentation. Label assumptions and unknowns.

## Knowledge gaps
Record only gaps that affect the next task. Do not build a textbook or mirror the repository.
"""
    files[project / ".maverick/STATE.md"] = """# Current state

## Now
- Configuration files installed; project adaptation and live subagent smoke test remain.

## Decisions to preserve
- Maverick is the main voice. Call other personalities only when they add value.
- Manual personality update only; no automatic evolution or benchmark cycle.

## Next
- Fill PROJECT.md and knowledge/domain.md from actual sources, then set their Status to READY.
- Run doctor. Dispatch mav_hacker and mav_inventor read-only to verify native loading; report their actual IDs and evidence.

## Last verification
- Native custom-agent execution: NOT_RUN. File installation is not proof of runtime integration.
"""
    for role in CHILDREN:
        files[project / f".codex/agents/mav_{role}.toml"] = compiled_role(role, read(personas / f"{role}.md"), {}, args.worker_model)
    # Unowned collisions are checked before changing AGENTS.md or config.toml.
    for path, content in files.items():
        ensure_owned(path, content)
    files[project / "AGENTS.md"] = merge_guidance(read(project / "AGENTS.md"))
    files[project / ".codex/config.toml"] = merge_config(read(project / ".codex/config.toml"))
    changed = write_all(project, files)
    return {"status": "installed_needs_adaptation", "changed": changed,
            "next": "Read the installed skill. Fill project knowledge from actual files, run doctor, then do a real named-child smoke test."}


def sync(args, new_prefs: dict | None = None) -> dict:
    project = args.project
    info = manifest(project)
    prefs = preferences(project) if new_prefs is None else new_prefs
    model = getattr(args, "worker_model", None)
    if model:
        info["worker_model"] = None if model == "inherit" else model
    files = {project / ".maverick/manifest.json": js(info)}
    for role in CHILDREN:
        base = skill_dir(project) / f"references/personas/{role}.md"
        if not base.is_file():
            raise ValueError(f"Missing personality source: {base}")
        path = project / f".codex/agents/mav_{role}.toml"
        content = compiled_role(role, read(base), prefs, info.get("worker_model"))
        ensure_owned(path, content, generated=True)
        files[path] = content
    if new_prefs is not None:
        files[project / ".maverick/preferences.json"] = js(new_prefs)
    changed = write_all(project, files)
    return {"status": "synced", "changed": changed,
            "next": "Reload adjusted rules explicitly. Use a new child for changed personality/model instructions; do not assume hot reload."}


def update(args) -> dict:
    manifest(args.project)
    prefs = preferences(args.project)
    if not re.fullmatch(r"[a-z][a-z0-9_-]{0,39}", args.key):
        raise ValueError("Rule key must be a short lower-case identifier, e.g. simple_changes.")
    rules = prefs.setdefault(args.persona, {})
    old = rules.get(args.key)
    if args.remove:
        if args.key not in rules:
            return {"status": "unchanged", "changed": [], "reason": "Rule not present."}
        del rules[args.key]
    else:
        if not args.rule or not args.rule.strip() or len(args.rule) > 700:
            raise ValueError("Provide a nonempty --rule of at most 700 characters.")
        if args.key not in rules and len(rules) >= 8:
            raise ValueError("This persona already has eight rules. Replace an existing rule instead of adding more.")
        if old == args.rule.strip():
            return {"status": "unchanged", "changed": []}
        rules[args.key] = args.rule.strip()
    result = sync(args, prefs)
    result.update({"status": "updated", "scope": "this_project", "persona": args.persona,
                   "rule_key": args.key, "before": old, "after": rules.get(args.key)})
    entry = {"at": now(), "persona": args.persona, "key": args.key, "before": old,
             "after": rules.get(args.key), "reason": args.because or "Explicit user update"}
    log = args.project / ".maverick/updates.jsonl"
    # A short journal supports undo/review without snapshots or an evaluation system.
    lines = read(log).splitlines()[-19:]
    lines.append(json.dumps(entry, ensure_ascii=False))
    write_all(args.project, {log: "\n".join(lines) + "\n"})
    return result


def doctor(args) -> dict:
    project = args.project
    errors, pending, notes = [], [], []
    try:
        info, prefs = manifest(project), preferences(project)
    except (ValueError, json.JSONDecodeError) as exc:
        return {"static": "FAIL", "project_context": "UNKNOWN", "native_runtime": "NOT_TESTED_BY_DOCTOR", "errors": [str(exc)]}
    dest = skill_dir(project)
    required = [dest / "SKILL.md", dest / "scripts/maverick.py", project / ".maverick/STATE.md",
                project / ".maverick/knowledge/INDEX.md", dest / "references/knowledge/INDEX.md"]
    required += [dest / f"references/personas/{r}.md" for r in ROLES]
    errors += [f"Missing: {p.relative_to(project)}" for p in required if not p.is_file()]
    skill = read(dest / "SKILL.md")
    if not skill.startswith("---\n") or not re.search(r"(?m)^name: maverick$", skill) or not re.search(r"(?m)^description: .+", skill):
        errors.append("Skill frontmatter is missing name/description.")
    if START not in read(project / "AGENTS.md") or END not in read(project / "AGENTS.md"):
        errors.append("AGENTS.md is missing the managed Maverick block.")
    try:
        cfg = tomllib.loads(read(project / ".codex/config.toml"))
        ac = cfg.get("agents", {})
        if not isinstance(ac, dict):
            errors.append("Project agents configuration is not a TOML table.")
            ac = {}
        if ac.get("enabled") is not True:
            errors.append("Project agents.enabled is not true.")
        if "max_threads" in ac and "max_concurrent_threads_per_session" in ac:
            errors.append("Both aliases for agent concurrency are present.")
    except tomllib.TOMLDecodeError as exc:
        errors.append(f"Invalid project TOML: {exc}")
    for role in CHILDREN:
        path = project / f".codex/agents/mav_{role}.toml"
        try:
            raw = read(path)
            cfg = tomllib.loads(raw)
            if cfg.get("name") != f"mav_{role}" or not cfg.get("description") or not cfg.get("developer_instructions"):
                errors.append(f"Missing required custom-agent fields: {path.name}")
            base = read(dest / f"references/personas/{role}.md")
            if raw != compiled_role(role, base, prefs, info.get("worker_model")):
                errors.append(f"Generated config is stale or edited: {path.name}; run sync.")
        except tomllib.TOMLDecodeError as exc:
            errors.append(f"Invalid role TOML {path.name}: {exc}")
    for name in ("PROJECT.md", "knowledge/domain.md"):
        body = read(project / ".maverick" / name)
        if not re.search(r"(?m)^Status: READY\s*$", body):
            pending.append(name)
        elif len(body.splitlines()) < 8:
            errors.append(f"Project context has no useful content: {name}")
    for index in (dest / "references/knowledge/INDEX.md", project / ".maverick/knowledge/INDEX.md"):
        for target in re.findall(r"\]\(([^)]+)\)", read(index)):
            if "://" not in target and not target.startswith("#") and not (index.parent / target.split("#")[0]).is_file():
                errors.append(f"Broken knowledge link in {index.name}: {target}")
    notes.append("Static checks cannot prove trust, model availability, current-session skill discovery or native child dispatch.")
    notes.append("Use INSTALL.md / the skill's initialization check to dispatch a real named child. Task names alone are not proof.")
    return {"static": "FAIL" if errors else "PASS", "project_context": "PENDING" if pending else "READY",
            "native_runtime": "NOT_TESTED_BY_DOCTOR", "pending": pending, "errors": errors, "notes": notes}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    for name in ("init", "doctor", "sync", "update"):
        p = commands.add_parser(name)
        p.add_argument("--project", type=lambda s: Path(s).expanduser().resolve(), default=Path.cwd())
        if name in ("init", "sync"):
            p.add_argument("--worker-model", help="An available model ID for Hacker; omitted means inherit. sync accepts inherit to clear.")
        if name == "init":
            p.add_argument("--name")
        if name == "update":
            p.add_argument("--persona", choices=ROLES, required=True)
            p.add_argument("--key", required=True, help="Reuse the same key to replace a rule.")
            action = p.add_mutually_exclusive_group(required=True)
            action.add_argument("--rule")
            action.add_argument("--remove", action="store_true")
            p.add_argument("--because", help="A short actual observation; omit private details.")
    args = parser.parse_args()
    try:
        result = globals()[args.command](args)
    except (ValueError, OSError, json.JSONDecodeError, tomllib.TOMLDecodeError) as exc:
        print(js({"status": "ERROR", "message": str(exc)}), end="", file=sys.stderr)
        return 1
    print(js(result), end="")
    if args.command == "doctor":
        return 1 if result["static"] == "FAIL" else 2 if result["project_context"] != "READY" else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
